reg = json.load(open("entity_registry.json"))
people = reg["people"]

# Build index of normalized canonical names + aliases
known: dict = {}
for pid, p in people.items():
    canon = p.get("canonical_name_he") or ""
    for n in [canon] + (p.get("aliases") or []):
        if n:
            known[norm(n)] = (pid, canon)

missing_critics = []
present_critics = []
for n in CRITICS:
    n = n.strip()
    if not n: continue
    nn = norm(n)
    if nn in known:
        present_critics.append((n, known[nn][1]))
    else:
        missing_critics.append(n)

missing_faculty = []
present_faculty = []
for n in FACULTY:
    n = n.strip()
    if not n: continue
    nn = norm(n)
    if nn in known:
        present_faculty.append((n, known[nn][1]))
    else:
        missing_faculty.append(n)

print(f"=== CRITICS ({len(CRITICS)}) ===")
print(f"  present:  {len(present_critics)}")
print(f"  missing:  {len(missing_critics)}")
print(f"\n=== FACULTY ({len(FACULTY)}) ===")
print(f"  present:  {len(present_faculty)}")
print(f"  missing:  {len(missing_faculty)}")

with open("data/gemini_research/missing_critics.txt", "w", encoding="utf-8") as f:
    f.write("\n".join(missing_critics))
with open("data/gemini_research/missing_faculty.txt", "w", encoding="utf-8") as f:
    f.write("\n".join(missing_faculty))
with open("data/gemini_research/present_summary.txt", "w", encoding="utf-8") as f:
    for n, c in present_critics + present_faculty:
        f.write(f"{n}\t→\t{c}\n")

print("\nWrote: missing_critics.txt, missing_faculty.txt, present_summary.txt")
