import json, re, unicodedata, sys

def norm(n):
    n = unicodedata.normalize("NFC", n or "").strip()
    n = re.sub(r"\s+", " ", n)
    # strip honorific prefixes that may differ
    n = re.sub(r"^(פרופ['׳`]\s+(אמריטוס\s+)?|ד[״'\"]?ר\s+)", "", n)
    n = n.replace("'", "").replace("׳", "").replace('"', "").replace("״", "")
    return n

